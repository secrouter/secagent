def test_to_dict_include_why_false_omits_why_keeps_counts_and_complete():
    """The dict a command RETURNS (printed to CLI stdout, forwarded verbatim by
    the pi extension into a model's context) must stay bounded regardless of
    how many units a run touched — `include_why=False` is how callers get that.
    """
    why = {"a.c": UnitState(state="failed", reason="parse error")}
    cov = Coverage(eligible=2, attempted=1, succeeded=0, partial=0, failed=1, skipped=1, why=why)
    d = cov.to_dict(include_why=False)
    assert "why" not in d
    assert d["eligible"] == 2
    assert d["attempted"] == 1
    assert d["succeeded"] == 0
    assert d["partial"] == 0
    assert d["failed"] == 1
    assert d["skipped"] == 1
    assert d["complete"] is False


def test_to_dict_default_includes_why_and_round_trips_through_json():
    """The full block (with `why`) goes into the JSON artifact on disk, so
    `to_dict()` must actually be JSON-serialisable end to end, not merely
    dict-shaped — a non-serialisable value here would only surface at write time
    on a real run.
    """
    why = {"a.c": UnitState(state="succeeded", reason="ok")}
    cov = Coverage(eligible=1, attempted=1, succeeded=1, partial=0, failed=0, skipped=0, why=why)
    d = cov.to_dict()
    assert d["why"] == {"a.c": {"state": "succeeded", "reason": "ok"}}
    round_tripped = json.loads(json.dumps(d))
    assert round_tripped == d


def test_coverage_to_dict_renders_multiple_domains():
    """A command with two populations (e.g. `analyze scan`'s translation-unit
    coverage and finding-triage coverage) emits two domains under `coverage`,
    not one merged/averaged block — this is the helper that renders that shape.
    """
    domains = {
        "files": Coverage(eligible=2, attempted=2, succeeded=2, partial=0, failed=0, skipped=0),
        "triage": Coverage(eligible=5, attempted=3, succeeded=2, partial=0, failed=1, skipped=2),
    }
    out = coverage_to_dict(domains, include_why=False)
    assert set(out) == {"files", "triage"}
    assert out["files"]["complete"] is True
    assert out["triage"]["complete"] is False
    assert "why" not in out["files"]


