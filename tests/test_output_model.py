def test_provenance_rejects_bare_string_model():
    """A bare `str` for `model` must be rejected by its OWN dedicated check:
    `for m in "gemma"` silently iterates characters, not model names, and
    something downstream doing exactly that is the concrete bug this guards
    against — the dedicated check exists specifically to name that failure mode
    in the error message, rather than relying on the generic "must be a list"
    check that would also catch a bare string as a side effect (a str is not a
    list either). `match` targets wording unique to the dedicated check so the
    test fails (mismatched message) if that check — rather than the generic
    one — is what gets deleted.
    """
    with pytest.raises(ValueError, match="iterating it yields individual characters"):
        Provenance(secagent_version="0.1.0", model="gemma", endpoint="http://x",
                   generated_at="2026-01-01T00:00:00Z", heuristic_only=False)


def test_provenance_accepts_list_of_models():
    """Silence test: the correct shape (a list of model name strings) must be
    accepted, including the multi-model case a docs run or a triaged analyze
    run actually produces (index-time model + render-time model, or a
    no-model producer alongside a triage model).
    """
    prov = Provenance(secagent_version="0.1.0", model=["gemma3:27b", "ikos"],
                       endpoint="http://x", generated_at="2026-01-01T00:00:00Z",
                       heuristic_only=False)
    assert prov.model == ["gemma3:27b", "ikos"]


def test_provenance_rejects_empty_string_in_model_list():
    """A list containing a blank/whitespace-only entry names no real model and
    is the same "placeholder that looks like an answer" failure mode as an
    empty `why` reason."""
    with pytest.raises(ValueError, match="list of non-empty strings"):
        Provenance(secagent_version="0.1.0", model=["gemma3:27b", "  "],
                   endpoint="http://x", generated_at="2026-01-01T00:00:00Z",
                   heuristic_only=False)


def test_provenance_rejects_heuristic_only_with_named_model():
    """`heuristic_only=True` together with a non-empty `model` is contradictory:
    a heuristic-fallback result was, by definition, not produced by any of the
    named models. Two evaluation agents each wasted a run unable to tell a
    working model from a broken endpoint from the heuristic fallback — this
    keeps the two signals from disagreeing with each other.
    """
    with pytest.raises(ValueError, match="is contradictory with a non-empty"):
        Provenance(secagent_version="0.1.0", model=["gemma3:27b"], endpoint="http://x",
                   generated_at="2026-01-01T00:00:00Z", heuristic_only=True)


def test_provenance_heuristic_only_with_empty_model_is_accepted():
    """Silence test: the actually-consistent heuristic-fallback shape
    (heuristic_only=True, model=[]) must not be rejected."""
    prov = Provenance(secagent_version="0.1.0", model=[], endpoint="http://x",
                       generated_at="2026-01-01T00:00:00Z", heuristic_only=True)
    assert prov.heuristic_only is True
    assert prov.model == []


def test_provenance_rejects_non_z_suffixed_timestamp():
    """`generated_at` must be UTC and say so unambiguously via a 'Z' suffix — a
    naive or offset timestamp without it leaves a reader guessing the timezone
    of every other timestamp in the same report.

    NOTE on isolation: this cannot be isolated from the fromisoformat guard
    below by choice of input either — with the Z-suffix check deleted, this
    exact offset-suffixed string reaches `self.generated_at[:-1] + "+00:00"`,
    which mangles the offset into something `fromisoformat` also rejects, so
    the guard fires anyway. Mutation-tested this directly. The distinctive
    `match` (this check's own wording, "ending in 'Z'") is what actually
    distinguishes the two — the fromisoformat guard's message says "is not a
    valid ISO-8601 timestamp" instead, which does not match.
    """
    with pytest.raises(ValueError, match="ending in 'Z'"):
        Provenance(secagent_version="0.1.0", model=[], endpoint="http://x",
                   generated_at="2026-01-01T00:00:00+02:00", heuristic_only=False)


def test_provenance_rejects_malformed_timestamp_despite_z_suffix():
    """The `fromisoformat` guard is a distinct check from the Z-suffix check: a
    string can satisfy "ends with Z" while still not being a real timestamp
    (e.g. an invalid month), and this exercises that branch specifically —
    the same mechanism that would let a hand-typed `generated_at` with a typo
    through if only the suffix were checked.
    """
    with pytest.raises(ValueError, match="is not a valid ISO-8601 timestamp"):
        Provenance(secagent_version="0.1.0", model=[], endpoint="http://x",
                   generated_at="2026-13-45T99:99:99Z", heuristic_only=False)


def test_provenance_now_produces_a_z_suffixed_timestamp_that_actually_parses():
    """`Provenance.now()` must produce a timestamp that both ends in 'Z' AND
    round-trips through real ISO-8601 parsing — `datetime.fromisoformat` does
    not accept a bare 'Z' suffix directly, so the test exercises the same
    normalisation a real consumer would need, rather than just checking
    `.endswith("Z")` and assuming the rest is well-formed.
    """
    prov = Provenance.now(model=["gemma3:27b"], endpoint="http://x")
    assert prov.generated_at.endswith("Z")
    parsed = datetime.fromisoformat(prov.generated_at[:-1] + "+00:00")
    assert parsed.tzinfo is not None
    now = datetime.now(UTC)
    assert abs((now - parsed).total_seconds()) < 60
    assert prov.secagent_version  # pulled from secagent.__version__, not invented


def test_provenance_to_dict_round_trips_through_json():
    """`Provenance.to_dict()` is written into report JSON alongside `coverage`,
    so it must be plain-JSON-serialisable, including the `model` list."""
    prov = Provenance.now(model=["gemma3:27b", "ikos"], endpoint="http://x",
                           heuristic_only=False)
    d = prov.to_dict()
    round_tripped = json.loads(json.dumps(d))
    assert round_tripped == d
    assert round_tripped["model"] == ["gemma3:27b", "ikos"]
