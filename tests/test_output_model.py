def test_fully_successful_unbounded_run_is_valid_and_complete():
    """The baseline honest case: eligible == attempted == succeeded, zero
    partial/failed/skipped, empty why. Must construct and report complete=True —
    if THIS is ever rejected, the validator is rejecting everything, which is as
    useless as rejecting nothing.
    """
    cov = Coverage(eligible=4, attempted=4, succeeded=4, partial=0, failed=0, skipped=0)
    assert cov.complete is True
    assert cov.to_dict(include_why=False)["complete"] is True


