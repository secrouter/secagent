# from_why
# --------------------------------------------------------------------------

_WHY_FIXTURES = [
    {},
    {"a.c": UnitState(state="succeeded", reason="ok")},
    {
        "a.c": UnitState(state="succeeded", reason="ok"),
        "b.c": UnitState(state="failed", reason="parse error"),
        "c.c": UnitState(state="skipped", reason="scan.max_files=2"),
    },
    {
        f"file{i}.c": UnitState(
            state=STATES[i % len(STATES)], reason=f"reason {i}"
        )
        for i in range(12)
    },
]


@pytest.mark.parametrize("why", _WHY_FIXTURES)
def test_from_why_derives_a_valid_coverage(why):
    """`from_why` is the anti-fabrication constructor: counts are tallied FROM
    `why`, so they cannot independently drift from it the way hand-typed
    integers could. Constructing over several generated `why` maps (including
    the empty one) proves the derivation itself always satisfies the invariant
    `Coverage.__post_init__` enforces.
    """
    cov = Coverage.from_why(why)
    assert cov.attempted == cov.succeeded + cov.partial + cov.failed
    assert cov.eligible == cov.attempted + cov.skipped
    for state in STATES:
        expected = sum(1 for u in why.values() if u.state == state)
        assert getattr(cov, state) == expected


def test_from_why_eligible_omitted_means_why_is_the_whole_population():
    """Omitting `eligible` derives it as len(why) — appropriate for a producer
    like scan that enumerates every eligible unit's outcome in `why`."""
    why = {
        "a.c": UnitState(state="succeeded", reason="ok"),
        "b.c": UnitState(state="skipped", reason="scan.max_files=1"),
    }
    cov = Coverage.from_why(why)
    assert cov.eligible == 2
    assert cov.complete is False  # b.c was skipped


def test_from_why_explicit_eligible_none_stays_unknowable():
    """Passing `eligible=None` explicitly must be preserved as None, distinct
    from the omitted-default case above — the two are NOT the same call, and a
    private sentinel (not None as the default) is what keeps them distinguishable.
    """
    why = {"a.c": UnitState(state="succeeded", reason="ok")}
    cov = Coverage.from_why(why, eligible=None)
    assert cov.eligible is None
    assert cov.complete is False


def test_from_why_omitted_and_explicit_none_differ():
    """Direct comparison of the two `from_why` call shapes on the same `why`,
    proving they really do produce different, both-correct results."""
    why = {"a.c": UnitState(state="succeeded", reason="ok")}
    omitted = Coverage.from_why(why)
    explicit_none = Coverage.from_why(why, eligible=None)
    assert omitted.eligible == 1
    assert explicit_none.eligible is None


def test_from_why_explicit_eligible_matching_len_why_is_accepted():
    """Passing an explicit int `eligible` that happens to equal `len(why)` (the
    same value the omitted-default case would compute) is redundant but valid —
    from_why does not special-case "was eligible passed at all" beyond the
    None-vs-omitted distinction."""
    why = {"a.c": UnitState(state="failed", reason="parse error")}
    cov = Coverage.from_why(why, eligible=1)
    assert cov.eligible == 1


def test_from_why_explicit_eligible_disagreeing_with_why_is_rejected():
    """from_why does NOT let a caller override eligible to a number the `why`
    tally cannot support: since attempted + skipped always equals len(why) for
    tallied counts, an eligible that names a bigger (or smaller) population than
    `why` actually accounts for still fails the same reconciliation check a
    hand-built Coverage would — from_why derives, it does not launder a wrong
    number past validation.
    """
    why = {"a.c": UnitState(state="failed", reason="parse error")}
    with pytest.raises(ValueError, match="does not equal attempted"):
        Coverage.from_why(why, eligible=5)


