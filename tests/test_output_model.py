"""Tests for `secagent.output`: the shared `Coverage` / `Provenance` primitives.

This repo has shipped a fake or self-inconsistent coverage block five separate
times under five different names (a scanner that silently truncated files, a
testgen that dropped unreadable files, a docs build that rendered 9 of 17
modules, an analyze pass that reported `tus_skipped: 0` for files never in the
compile database). The point of `Coverage` is that its own numbers cannot be
inconsistent with each other, and these tests exist to prove that every rule
that makes that true actually rejects the input it claims to reject — and,
just as importantly, that it does not reject the honest neighbouring case.
"""

from __future__ import annotations

import itertools
import json
from datetime import UTC, datetime

import pytest

from secagent.output import STATES, Coverage, Provenance, UnitState, coverage_to_dict

# Keeping the exhaustive sweep small (0..3 per count) makes the invariant test a
# genuine property test over hundreds of concrete cases while still running in
# well under a second — the point is coverage of the *shape* of the invariant
# (every combination of zero/nonzero/equal/unequal states), not the specific
# magnitudes.
_SMALL = range(4)


def _valid(succeeded: int, partial: int, failed: int, skipped: int) -> Coverage:
    """Build the unique valid `Coverage` for one (succeeded, partial, failed, skipped)."""
    attempted = succeeded + partial + failed
    eligible = attempted + skipped
    return Coverage(
        eligible=eligible,
        attempted=attempted,
        succeeded=succeeded,
        partial=partial,
        failed=failed,
        skipped=skipped,
    )


# --------------------------------------------------------------------------
# The core invariant, exhaustively over small counts.
# --------------------------------------------------------------------------


def test_invariant_holds_and_complete_is_exact_over_all_small_combinations():
    """For every (succeeded, partial, failed, skipped) in range(4)**4, the derived
    Coverage must construct, and `complete` must match its definition exactly.

    This is the property test called for by the task: hundreds of concrete cases
    generated by itertools.product rather than three hand-picked examples, so it
    covers combinations (e.g. succeeded=0 and partial=0 and failed=0 and skipped=0,
    or eligible=0) that hand-picked examples tend to skip.
    """
    for s, p, f, k in itertools.product(_SMALL, repeat=4):
        cov = _valid(s, p, f, k)
        expected_complete = (cov.attempted == cov.eligible) and p == 0 and f == 0
        assert cov.complete == expected_complete, (s, p, f, k)


def test_perturbing_any_single_count_by_one_breaks_the_invariant():
    """Every field of a valid Coverage is load-bearing: nudging exactly one of the
    six numeric fields by +-1, holding the rest fixed, must always raise.

    This is the mechanism-level version of "the numbers must add up" — it isn't
    enough that some inconsistent inputs raise, EVERY single-field perturbation
    away from a valid point must raise, or the invariant has a blind spot.
    """
    checked = 0
    for s, p, f, k in itertools.product(_SMALL, repeat=4):
        attempted = s + p + f
        eligible = attempted + k
        base = {"eligible": eligible, "attempted": attempted, "succeeded": s,
                "partial": p, "failed": f, "skipped": k}
        for field_name in base:
            for delta in (1, -1):
                bad = dict(base)
                bad[field_name] = base[field_name] + delta
                with pytest.raises(ValueError):
                    Coverage(**bad)
                checked += 1
    assert checked == (4**4) * 6 * 2


def test_complete_is_false_whenever_eligible_is_none_for_every_combination():
    """`complete` must never be inferred when the population is unknowable.

    `secagent analyze ingest` reads findings from an external SARIF report and has
    no way to see the translation-unit population, so `eligible=None`. Guards
    against a plausible-looking regression: "if attempted > 0 and failed == 0
    and partial == 0, call it complete" would accidentally treat an unknowable
    population as fully covered.
    """
    for s, p, f, k in itertools.product(_SMALL, repeat=4):
        attempted = s + p + f
        cov = Coverage(eligible=None, attempted=attempted, succeeded=s,
                        partial=p, failed=f, skipped=k)
        assert cov.complete is False, (s, p, f, k)


# --------------------------------------------------------------------------
# Individual validation rules: a rejection test paired with a silence test.
# --------------------------------------------------------------------------


def test_negative_count_rejected():
    """Rule 1: every count must be >= 0. A negative count cannot arise from any
    real tally of units and signals a producer that built the numbers by hand.

    NOTE on isolation: a negative succeeded/partial/failed/skipped can never be
    isolated from rule 5 by choice of input alone. Rule 5 loops over all four
    STATES unconditionally and compares a tally that is always >= 0 (why_counts)
    against the reported count — so whenever a reported count is negative, "0 (or
    more) > negative" is true no matter what `why` contains, and rule 5 fires
    too. Mutation-tested this directly: with rule 1's own check deleted, this
    exact input still raises ValueError, just from rule 5's branch instead ("why
    cannot name more units..."). The `match` below is rule 1's own distinctive
    wording, so the test still correctly fails (wrong message) when rule 1 is
    the one removed, even though *some* ValueError survives either way.
    """
    with pytest.raises(ValueError, match="must be >= 0, got -1"):
        Coverage(eligible=0, attempted=0, succeeded=-1, partial=0, failed=1, skipped=0)


def test_zero_counts_are_accepted():
    """Silence test for rule 1: an all-zero Coverage (a domain with no eligible
    units at all, e.g. `docs` diagrams on a repo with none) is legitimate and
    must not be rejected by the >= 0 check.
    """
    cov = Coverage(eligible=0, attempted=0, succeeded=0, partial=0, failed=0, skipped=0)
    assert cov.complete is True


def test_negative_eligible_rejected():
    """Rule 1 (eligible variant): `eligible` is `int | None`, and when it IS an
    int it must still be >= 0 — `None` is the only legal way to say "unknown".

    NOTE on isolation: like the plain negative-count case, this cannot be
    isolated from rule 3 by choice of input — rule 1's own check keeps
    `attempted`/`skipped` non-negative, so `attempted + skipped` can never equal
    a negative `eligible`, and rule 3 necessarily also fires. Mutation-tested:
    with rule 1's eligible check deleted, this input still raises, via rule 3's
    "does not equal attempted(...)" message. The distinctive `match` below is
    what actually distinguishes "rule 1 fired" from "rule 3 fired instead".
    """
    with pytest.raises(ValueError, match="must be None or >= 0"):
        Coverage(eligible=-1, attempted=0, succeeded=0, partial=0, failed=0, skipped=0)


def test_none_eligible_is_accepted_without_reconciliation():
    """Silence test: `eligible=None` (population genuinely unknowable, e.g.
    `analyze ingest` from an external SARIF report) must construct cleanly and
    skip the eligible == attempted + skipped reconciliation entirely.
    """
    cov = Coverage(eligible=None, attempted=3, succeeded=2, partial=0, failed=1, skipped=100)
    assert cov.eligible is None
    assert cov.complete is False


def test_attempted_not_matching_sum_rejected():
    """Rule 2: `attempted` must equal succeeded + partial + failed. This is
    exactly the bug where a report's own files_analyzed/files_failed/files_partial
    trio could disagree with each other because nothing forced them to reconcile.
    """
    with pytest.raises(ValueError, match="does not equal succeeded"):
        Coverage(eligible=10, attempted=8, succeeded=5, partial=1, failed=1, skipped=2)


def test_attempted_matching_sum_is_accepted():
    """Silence test for rule 2: the honest neighbouring case (attempted correctly
    equal to the sum of the three outcome counts) must not be rejected.
    """
    cov = Coverage(eligible=10, attempted=7, succeeded=5, partial=1, failed=1, skipped=3)
    assert cov.attempted == 7


def test_eligible_not_matching_attempted_plus_skipped_rejected():
    """Rule 3: when eligible is known, eligible must equal attempted + skipped.
    This is the "files_skipped_by_cap derived from selection, files_analyzed
    derived from what ran, and nothing reconciled the two" defect, generalised.
    """
    with pytest.raises(ValueError, match="does not equal attempted"):
        Coverage(eligible=11, attempted=8, succeeded=6, partial=1, failed=1, skipped=2)


def test_eligible_matching_attempted_plus_skipped_is_accepted():
    """Silence test for rule 3: eligible correctly reconciled with attempted +
    skipped must construct without complaint."""
    cov = Coverage(eligible=10, attempted=8, succeeded=6, partial=1, failed=1, skipped=2)
    assert cov.eligible == 10


def test_why_state_outside_states_rejected():
    """Rule 4a: every `why` entry's state must be one of the four STATES. A typo
    like "sucess" or a stray "attempted" (which is not a state — see module
    docstring) must not silently pass through into a report artifact.
    """
    with pytest.raises(ValueError, match="is not one of"):
        Coverage(eligible=1, attempted=1, succeeded=1, partial=0, failed=0, skipped=0,
                 why={"a.c": UnitState(state="attempted", reason="bogus")})


def test_why_state_in_states_is_accepted():
    """Silence test for rule 4a: a `why` entry using one of the four real
    STATES values must be accepted."""
    cov = Coverage(eligible=1, attempted=0, succeeded=0, partial=0, failed=0, skipped=1,
                    why={"a.c": UnitState(state="skipped", reason="scan.max_files=0")})
    assert cov.why["a.c"].state == "skipped"


def test_why_blank_reason_rejected():
    """Rule 4b: a `why` entry's reason must be non-empty after stripping
    whitespace. A reason of "" or "   " names no cause at all and is exactly the
    "skipped: 0" style placeholder this module exists to make impossible.
    """
    with pytest.raises(ValueError, match="empty reason"):
        Coverage(eligible=1, attempted=0, succeeded=0, partial=0, failed=0, skipped=1,
                 why={"a.c": UnitState(state="skipped", reason="   ")})


def test_why_nonblank_reason_is_accepted():
    """Silence test for rule 4b: a real, non-empty reason must not be rejected."""
    cov = Coverage(eligible=1, attempted=0, succeeded=0, partial=0, failed=0, skipped=1,
                    why={"a.c": UnitState(state="skipped", reason="scan.max_files=0")})
    assert cov.why["a.c"].reason == "scan.max_files=0"


def test_why_names_more_failures_than_failed_count_rejected():
    """Rule 5, explicitly required by the task: naming three failed units in
    `why` while reporting failed=1 means the headline count understates the
    detail map sitting right next to it — the detail is presumably the true one.

    eligible/attempted/succeeded/partial/failed/skipped here are deliberately
    chosen to individually satisfy rules 1-3 (attempted == sum of outcomes,
    eligible == attempted + skipped) so that this test isolates rule 5 rather
    than incidentally tripping over the attempted/eligible reconciliation
    first — three "failed" `why` entries against a reported `failed=1`, with
    everything else self-consistent.
    """
    why = {
        "a.c": UnitState(state="failed", reason="parse error"),
        "b.c": UnitState(state="failed", reason="timeout"),
        "c.c": UnitState(state="failed", reason="OOM"),
    }
    with pytest.raises(ValueError, match="why cannot name more"):
        Coverage(eligible=1, attempted=1, succeeded=0, partial=0, failed=1, skipped=0, why=why)


def test_why_count_matching_reported_count_is_accepted():
    """Silence test for rule 5: naming exactly as many failed units in `why` as
    the `failed` count reports must be accepted, not just "fewer than"."""
    why = {
        "a.c": UnitState(state="failed", reason="parse error"),
        "b.c": UnitState(state="failed", reason="timeout"),
    }
    cov = Coverage(eligible=2, attempted=2, succeeded=0, partial=0, failed=2, skipped=0, why=why)
    assert cov.failed == 2


